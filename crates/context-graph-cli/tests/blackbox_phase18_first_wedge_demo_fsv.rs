fn init_git_repo(repo: &Path) {
    let output = Command::new("git")
        .arg("init")
        .arg(repo)
        .output()
        .expect("spawn git init");
    assert!(
        output.status.success(),
        "git init failed\nstdout={}\nstderr={}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    must_git(repo, &["config", "user.email", "phase18@example.test"]);
    must_git(repo, &["config", "user.name", "Phase18 Test"]);
    fs::write(repo.join("Cargo.lock"), cargo_lock("1.5.1")).expect("write initial lockfile");
    must_git(repo, &["add", "Cargo.lock"]);
    must_git(
        repo,
        &["commit", "-m", "initial vulnerable dependency fixture"],
    );
}

fn github_repo() -> (String, String) {
    let locator = std::env::var("BBX_GITHUB_TICKET_TEST_REPO")
        .ok()
        .filter(|value| !value.trim().is_empty())
        .or_else(|| {
            std::env::var("BBX_GITHUB_TEST_REPO")
                .ok()
                .filter(|value| !value.trim().is_empty())
        })
        .unwrap_or_else(|| "actions/checkout".to_string());
    let parts = locator.trim().split('/').collect::<Vec<_>>();
    assert_eq!(
        parts.len(),
        2,
        "BBX_GITHUB_TEST_REPO must be OWNER/REPO, found {locator:?}"
    );
    (parts[0].to_string(), parts[1].to_string())
}

fn github_api_json(path_and_query: &str) -> Value {
    let mut command = Command::new("curl");
    command
        .arg("-fsSL")
        .arg("-H")
        .arg("Accept: application/vnd.github+json")
        .arg("-H")
        .arg("X-GitHub-Api-Version: 2022-11-28")
        .arg("-H")
        .arg("User-Agent: contextgraph-blackbox-phase18-tests");

    if let Some(token) = std::env::var("BBX_GITHUB_TOKEN")
        .ok()
        .filter(|value| !value.trim().is_empty())
        .or_else(|| {
            std::env::var("GITHUB_TOKEN")
                .ok()
                .filter(|value| !value.trim().is_empty())
        })
    {
        command
            .arg("-H")
            .arg(format!("Authorization: Bearer {token}"));
    }

    let output = command
        .arg(format!("https://api.github.com/{path_and_query}"))
        .output()
        .expect("spawn curl for live GitHub source-of-truth read");
    assert!(
        output.status.success(),
        "GitHub source-of-truth curl failed\npath={path_and_query}\nstatus={:?}\nstdout={}\nstderr={}",
        output.status.code(),
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    serde_json::from_slice(&output.stdout).expect("GitHub source-of-truth JSON")
}

fn extract_first_url(text: &str) -> Option<String> {
    let mut best_start = None;
    for marker in ["https://", "http://"] {
        if let Some(index) = text.find(marker) {
            best_start = Some(best_start.map_or(index, |current: usize| current.min(index)));
        }
    }
    let start = best_start?;
    let tail = &text[start..];
    let end = tail
        .find(|ch: char| {
            ch.is_whitespace() || matches!(ch, ')' | ']' | '}' | '>' | '"' | '\'' | '`' | '|')
        })
        .unwrap_or(tail.len());
    let url = tail[..end]
        .trim_end_matches(['.', ',', ';', ':', ')', ']'])
        .to_string();
    if url.starts_with("http://") || url.starts_with("https://") {
        Some(url)
    } else {
        None
    }
}

fn discover_github_fixture() -> GithubFixture {
    let (owner, repo) = github_repo();
    let pulls = github_api_json(&format!(
        "repos/{owner}/{repo}/pulls?state=open&per_page=10"
    ));
    let pr = pulls
        .as_array()
        .and_then(|items| items.first())
        .expect("fixture repository must expose at least one open PR");
    let pr_number = pr["number"].as_u64().expect("fixture PR number");

    let issues = github_api_json(&format!(
        "repos/{owner}/{repo}/issues?state=open&per_page=100"
    ));
    let issue = issues
        .as_array()
        .and_then(|items| {
            items.iter().find(|item| {
                item.get("pull_request").is_none()
                    && item
                        .get("body")
                        .and_then(Value::as_str)
                        .and_then(extract_first_url)
                        .is_some()
            })
        })
        .expect("fixture repository must expose an open issue body containing an http(s) URL");
    let issue_number = issue["number"].as_u64().expect("fixture issue number");
    let evidence_url =
        extract_first_url(issue["body"].as_str().expect("fixture issue body")).expect("URL");

    let runs = github_api_json(&format!(
        "repos/{owner}/{repo}/actions/runs?status=success&per_page=10"
    ));
    let run = runs["workflow_runs"]
        .as_array()
        .and_then(|items| items.first())
        .expect("fixture repository must expose at least one successful workflow run");
    GithubFixture {
        owner,
        repo,
        pr_number,
        issue_number,
        evidence_url,
        workflow_run_id: run["id"].as_u64().expect("workflow run id"),
        workflow_status: run["status"].as_str().expect("workflow status").to_string(),
        workflow_conclusion: run["conclusion"]
            .as_str()
            .expect("workflow conclusion")
            .to_string(),
    }
}

