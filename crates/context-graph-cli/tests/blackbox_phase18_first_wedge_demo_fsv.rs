//! BlackBoxFix Phase 18 first-wedge demo FSV tests.
//!
//! These tests execute the real CLI against a real SQLite ledger, a real local
//! Git repository, real scanner artifact files, and live GitHub/GitHub Actions
//! source-of-truth reads. The final assertions inspect the physical ledger and
//! package files directly; no mocked connector, database, or filesystem state is
//! used.

