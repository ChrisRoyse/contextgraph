#!/usr/bin/env bash
# combine_docs.sh — combine all mejepasystem/NN_*.md files (in numeric order)
# into a single mejepasystem-combined.md in this directory.
#
# Usage:
#   bash combine_docs.sh          # writes mejepasystem-combined.md
#   bash combine_docs.sh out.md   # writes to custom output path
set -euo pipefail

cd "$(dirname "$0")"

OUT="${1:-mejepasystem-combined.md}"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

# Collect NN_*.md files (00..99 prefix), numerically sorted.
mapfile -t FILES < <(find . -maxdepth 1 -type f -name '[0-9][0-9]_*.md' | sort -V)

if [[ "${#FILES[@]}" -eq 0 ]]; then
  echo "combine_docs.sh: no NN_*.md files found in $(pwd)" >&2
  exit 1
fi

BUILT_AT="$(date -u +%FT%TZ)"

{
  printf '# ME-JEPA System Documentation — Combined\n\n'
  printf '> Auto-generated by combine_docs.sh. Source files concatenated in numeric order.\n'
  printf '> Built at: %s\n' "$BUILT_AT"
  printf '> Source count: %s files\n\n' "${#FILES[@]}"
  printf -- '---\n\n'

  printf '## Table of contents\n\n'
  for f in "${FILES[@]}"; do
    base="$(basename "$f")"
    # Read first heading from each file (strip leading "# " and trailing whitespace).
    title="$(grep -m1 -E '^# ' "$f" | sed -E 's/^# +//; s/[[:space:]]+$//' || true)"
    [[ -z "$title" ]] && title="$base"
    # Build a github-style anchor that matches our normalized H2 headers below.
    anchor="$(printf '%s' "$base" | tr '[:upper:]' '[:lower:]' | sed 's/\.md$//' | tr -c 'a-z0-9' '-' | sed 's/-\+/-/g; s/^-//; s/-$//')"
    printf -- '- [%s](#%s) — `%s`\n' "$title" "$anchor" "$base"
  done
  printf '\n---\n\n'

  for f in "${FILES[@]}"; do
    base="$(basename "$f")"
    anchor="$(printf '%s' "$base" | tr '[:upper:]' '[:lower:]' | sed 's/\.md$//' | tr -c 'a-z0-9' '-' | sed 's/-\+/-/g; s/^-//; s/-$//')"
    sha="$(sha256sum "$f" | awk '{print $1}')"
    lines="$(wc -l < "$f")"
    printf '<a id="%s"></a>\n\n' "$anchor"
    printf -- '<!-- ===== BEGIN: %s (sha256:%s, %s lines) ===== -->\n\n' "$base" "$sha" "$lines"
    # Shift every heading by one level so the combined doc has a clean H1.
    # `# foo` -> `## foo`, `## foo` -> `### foo`, etc. Code-fenced lines are left alone.
    awk '
      BEGIN { infence = 0 }
      {
        if ($0 ~ /^```/) { infence = !infence; print; next }
        if (!infence && $0 ~ /^#+ /) { print "#" $0; next }
        print
      }
    ' "$f"
    printf '\n\n<!-- ===== END: %s ===== -->\n\n---\n\n' "$base"
  done

  printf '## End of combined document\n'
  printf '\nGenerated %s from %s source files.\n' "$BUILT_AT" "${#FILES[@]}"
} > "$TMP"

mv "$TMP" "$OUT"
size="$(wc -c < "$OUT")"
lines="$(wc -l < "$OUT")"
echo "wrote $OUT  (${lines} lines, ${size} bytes, from ${#FILES[@]} source files)"
