#!/usr/bin/env python3
"""Combine the 15 numbered whitepaper files (00_*.md through 14_*.md) in this
directory into a single Markdown document, in numerical order, with a generated
table of contents and per-section separators.

Output: MEJEPA_WHITEPAPER_COMBINED.md in this same directory.

Usage:
    python3 combine_whitepaper.py            # default output path
    python3 combine_whitepaper.py --output OTHER.md
    python3 combine_whitepaper.py --dry-run  # print would-include list, write nothing

The script is idempotent: rerunning it overwrites the combined file with the
current state of the source files. Fail-closed: refuses to write if any source
file is missing, unreadable, or has a duplicate numeric prefix.
"""

from __future__ import annotations

import argparse
import re
import sys
from datetime import datetime, timezone
from pathlib import Path


SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_OUTPUT = SCRIPT_DIR / "MEJEPA_WHITEPAPER_COMBINED.md"
FILE_PATTERN = re.compile(r"^(\d{2})_[A-Z][A-Z0-9_]*\.md$")
TITLE_PATTERN = re.compile(r"^#\s+(.+?)\s*$")


def discover_sections(directory: Path) -> list[tuple[int, Path]]:
    """Find every NN_*.md source file. Returns sorted by numeric prefix.

    Fail-closed: raises if a duplicate prefix is found.
    """
    seen: dict[int, Path] = {}
    for path in directory.iterdir():
        if not path.is_file():
            continue
        match = FILE_PATTERN.match(path.name)
        if not match:
            continue
        prefix = int(match.group(1))
        if prefix in seen:
            raise RuntimeError(
                f"duplicate numeric prefix {prefix:02d} for "
                f"{seen[prefix].name} and {path.name}"
            )
        seen[prefix] = path
    if not seen:
        raise RuntimeError(f"no whitepaper source files found in {directory}")
    return sorted(seen.items(), key=lambda item: item[0])


def extract_title(path: Path) -> str:
    """Return the text of the first level-1 heading in the file, or the
    filename stem if no heading is present.
    """
    try:
        with path.open(encoding="utf-8") as fh:
            for line in fh:
                title_match = TITLE_PATTERN.match(line)
                if title_match:
                    return title_match.group(1)
    except OSError as exc:
        raise RuntimeError(f"cannot read {path}: {exc}") from exc
    return path.stem


def render_combined(
    sections: list[tuple[int, Path]],
    *,
    source_dir: Path,
) -> str:
    """Build the combined Markdown body."""
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    titles = [(idx, path, extract_title(path)) for idx, path in sections]

    header_lines = [
        "# ME-JEPA-Code Whitepaper — Combined",
        "",
        f"**Generated:** {timestamp}",
        f"**Source directory:** `{source_dir}`",
        f"**Sections:** {len(titles)} files concatenated in numeric order",
        "**Generator:** `combine_whitepaper.py`",
        "",
        "> This file is auto-generated by concatenating the 15 numbered source",
        "> files (`00_*.md` through `14_*.md`) in this directory. Edit the source",
        "> files; regenerate this combined view by re-running",
        "> `python3 combine_whitepaper.py`.",
        "",
        "---",
        "",
        "## Table of Contents",
        "",
    ]
    for idx, path, title in titles:
        slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
        anchor = f"section-{idx:02d}-{slug}"
        header_lines.append(f"- [{idx:02d} — {title}](#{anchor}) (`{path.name}`)")
    header_lines.extend(["", "---", ""])

    body_parts: list[str] = ["\n".join(header_lines)]
    for idx, path, title in titles:
        slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
        anchor = f"section-{idx:02d}-{slug}"
        section_header = (
            f"<a id=\"{anchor}\"></a>\n\n"
            f"<!-- ====================================================== -->\n"
            f"<!-- Section {idx:02d} — source: {path.name}                -->\n"
            f"<!-- ====================================================== -->\n\n"
        )
        try:
            source_text = path.read_text(encoding="utf-8")
        except OSError as exc:
            raise RuntimeError(f"cannot read {path}: {exc}") from exc
        # Strip a trailing newline so the joiner produces clean spacing.
        body_parts.append(section_header + source_text.rstrip() + "\n")
    return "\n\n---\n\n".join(body_parts) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=f"output Markdown path (default: {DEFAULT_OUTPUT.name})",
    )
    parser.add_argument(
        "--source-dir",
        type=Path,
        default=SCRIPT_DIR,
        help=f"source directory (default: {SCRIPT_DIR})",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="list the source files that would be combined; do not write output",
    )
    args = parser.parse_args()

    source_dir: Path = args.source_dir.resolve()
    output_path: Path = args.output.resolve()

    if not source_dir.is_dir():
        print(f"error: source directory does not exist: {source_dir}", file=sys.stderr)
        return 2

    try:
        sections = discover_sections(source_dir)
    except RuntimeError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    print(f"found {len(sections)} source files:")
    for idx, path in sections:
        print(f"  {idx:02d} {path.name}")

    if args.dry_run:
        print("\n--dry-run; no output written")
        return 0

    try:
        combined = render_combined(sections, source_dir=source_dir)
    except RuntimeError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(combined, encoding="utf-8")
    byte_count = output_path.stat().st_size
    line_count = combined.count("\n")
    print(
        f"\nwrote {output_path.name}: {line_count} lines, "
        f"{byte_count:,} bytes ({byte_count / 1024:.1f} KB)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
