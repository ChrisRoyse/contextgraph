#!/usr/bin/env python3
"""Build the OPTIMAL Shakespeare training dataset using ALL Context Graph signals.

This script uses every signal type for its proper purpose:
- Content (2,770 memories) → SFT targets via enhanced prompts
- Typed edges (42,700 relationships) → graph-continuation SFT examples
- Contrastive pairs (12,567) → DPO (already built)
- Adversarial (285) → robustness
- Creative (93) → modern topic coverage
- Importance scores → training weights
- Constellation scores → work-style conditioning

Usage:
    python3 scripts/shakespeare_build_optimal_dataset.py
"""
from __future__ import annotations
import argparse, json, os, random, sys, time
from pathlib import Path
from collections import defaultdict

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _gemma_shakespeare_lib import Rpc

SYS_BASE = (
    "You are William Shakespeare. Write ONLY in early modern English — use thee, "
    "thou, thy, thine, hast, dost, doth, ye, prithee, forsooth, hark, wherefore, "
    "methinks, 'tis, 'twas, and similar period vocabulary. Use iambic rhythm where "
    "natural. Draw imagery from nature, stars, seasons, love, death, honour, and "
    "kingship. Write verse OR prose in Shakespeare's voice — NOT stage directions, "
    "NOT character names, NOT scene headers. Just beautiful Shakespearean writing "
    "about the topic the user asks about. Keep responses under 100 words."
)

EDGE_TYPES = {0: "causal", 1: "temporal", 2: "semantic", 3: "entity", 4: "graph", 5: "structural"}

# Prompt templates for graph-continuation examples
CONTINUATION_PROMPTS = {
    "entity": [
        "Tell me more about these characters and what befalls them",
        "What happens to the people in this tale?",
        "Continue the story of these characters",
        "What fate awaits the figures in this drama?",
    ],
    "graph": [
        "What connects to this theme?",
        "Tell me what follows from this",
        "What other truths relate to this?",
        "Expand upon this thought",
    ],
    "causal": [
        "What consequences follow from this?",
        "What does this lead to?",
        "Tell me the aftermath of this event",
        "What is caused by this?",
    ],
    "temporal": [
        "What happens next in the story?",
        "Continue from where this left off",
        "Tell me the next part of this tale",
        "What follows after this scene?",
    ],
    "semantic": [
        "Tell me something with a similar meaning",
        "Express a related thought",
        "What echoes this sentiment?",
        "Speak more on this same theme",
    ],
}


def make_sft(prompt, response, system_extra="", source="", meta=None):
    system = SYS_BASE
    if system_extra:
        system = f"{SYS_BASE}\n{system_extra}"
    ex = {
        "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": prompt},
            {"role": "assistant", "content": response},
        ],
        "_meta": {"prompt_source": source},
    }
    if meta:
        ex["_meta"].update(meta)
    return ex


def work_from_session(sid):
    if not sid:
        return "General"
    return sid.replace("shakespeare-", "").replace("-", " ").title()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.expanduser(
        "~/.contextgraph/training/shakespeare_sft_optimal.jsonl"))
    ap.add_argument("--max-graph-examples", type=int, default=3000,
                    help="Max graph-continuation examples to generate")
    args = ap.parse_args()

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)

    # ================================================================
    # STEP 1: Load pre-built data sources
    # ================================================================
    training_dir = Path(os.path.expanduser("~/.contextgraph/training"))

    # Enhanced prompts (5,348 — modern prompts generated by Gemma)
    enhanced = []
    enhanced_path = training_dir / "shakespeare_sft_enhanced.jsonl"
    if enhanced_path.exists():
        with open(enhanced_path) as f:
            enhanced = [json.loads(l) for l in f]
    print(f"[optimal] Enhanced SFT: {len(enhanced)}", file=sys.stderr)

    # Adversarial boost (285 — language, code, break, mixed)
    adversarial = []
    adv_path = training_dir / "shakespeare_adversarial_boost.jsonl"
    if adv_path.exists():
        with open(adv_path) as f:
            adversarial = [json.loads(l) for l in f]
    print(f"[optimal] Adversarial: {len(adversarial)}", file=sys.stderr)

    # Creative (93 — Gemma-generated Shakespeare about modern topics)
    creative = []
    creative_path = training_dir / "shakespeare_sft_creative.jsonl"
    if creative_path.exists():
        with open(creative_path) as f:
            creative = [json.loads(l) for l in f]
    print(f"[optimal] Creative: {len(creative)}", file=sys.stderr)

    # ================================================================
    # STEP 2: Generate graph-continuation examples from typed edges
    # ================================================================
    print(f"[optimal] Connecting to daemon for graph edges...", file=sys.stderr)
    rpc = Rpc()

    # Get all memory IDs
    all_ids = []
    offset = 0
    while True:
        r = rpc.call("list_training_records",
                      {"limit": 1000, "offset": offset, "includeShape": False}, timeout=60)
        recs = r.get("records", [])
        if not recs:
            break
        all_ids.extend(rec["memory_id"] for rec in recs)
        offset += 1000
        if len(recs) < 1000:
            break
    print(f"[optimal] {len(all_ids)} memories", file=sys.stderr)

    # Build content cache and edge graph
    print(f"[optimal] Building content cache and edge graph...", file=sys.stderr)
    content_cache = {}
    work_cache = {}
    importance_cache = {}
    edge_graph = defaultdict(list)  # source → [(target, edge_type, weight)]
    t0 = time.time()

    for i, mid in enumerate(all_ids):
        if i > 0 and i % 200 == 0:
            elapsed = time.time() - t0
            print(f"[optimal] {i}/{len(all_ids)} cached, "
                  f"{sum(len(v) for v in edge_graph.values())} edges, "
                  f"{elapsed:.0f}s", file=sys.stderr)

        try:
            rec = rpc.call("get_training_record", {
                "memoryId": mid, "includeVectors": False
            }, timeout=30)
        except Exception:
            continue

        content = rec.get("content", "")
        if not content or len(content.strip()) < 30:
            continue

        content_cache[mid] = content
        work_cache[mid] = work_from_session(rec.get("session_id", ""))
        importance_cache[mid] = rec.get("importance", 0.5)

        # Collect outgoing edges
        for edge in rec.get("outgoing_edges_detail", []):
            peer = edge.get("peer_id", "")
            etype = edge.get("edge_type", -1)
            weight = edge.get("weight", 0.0)
            if peer and etype >= 0:
                edge_graph[mid].append((peer, etype, weight))

    total_edges = sum(len(v) for v in edge_graph.values())
    print(f"[optimal] Cache built: {len(content_cache)} memories, {total_edges} edges, "
          f"{time.time()-t0:.0f}s", file=sys.stderr)

    rpc.close()

    # Generate continuation examples from edges
    print(f"[optimal] Generating graph-continuation examples...", file=sys.stderr)
    graph_examples = []

    # Sort edges by weight (highest first) for quality
    all_edges = []
    for src, targets in edge_graph.items():
        for tgt, etype, weight in targets:
            if tgt in content_cache and src in content_cache:
                all_edges.append((src, tgt, etype, weight))

    # Sort by weight descending — highest-quality relationships first
    all_edges.sort(key=lambda x: -x[3])
    print(f"[optimal] {len(all_edges)} valid edges to mine", file=sys.stderr)

    used_pairs = set()
    for src, tgt, etype, weight in all_edges:
        if len(graph_examples) >= args.max_graph_examples:
            break

        # Avoid duplicate pairs
        pair_key = (src, tgt)
        if pair_key in used_pairs:
            continue
        used_pairs.add(pair_key)

        src_content = content_cache[src]
        tgt_content = content_cache[tgt]
        src_work = work_cache.get(src, "General")
        tgt_work = work_cache.get(tgt, "General")

        # Get edge type name
        etype_name = EDGE_TYPES.get(etype, "semantic")

        # Get prompt templates for this edge type
        templates = CONTINUATION_PROMPTS.get(etype_name,
                                              CONTINUATION_PROMPTS["semantic"])
        prompt = random.choice(templates)

        # The example: prompt about what connects → target content
        # System prompt includes source context (first 100 chars)
        src_snippet = src_content[:100].replace("\n", " ").strip()
        system_extra = f"Style: {tgt_work}. Context: the user is asking about \"{src_snippet}...\""

        graph_examples.append(make_sft(
            prompt, tgt_content,
            system_extra=system_extra,
            source=f"graph_{etype_name}",
            meta={
                "edge_type": etype_name,
                "edge_weight": round(weight, 3),
                "src_work": src_work,
                "tgt_work": tgt_work,
                "src_id": src[:8],
                "tgt_id": tgt[:8],
            },
        ))

    # Also create "same work, different scene" examples using high-weight entity edges
    # These teach the model about character/theme consistency within a work
    work_memories = defaultdict(list)
    for mid, work in work_cache.items():
        work_memories[work].append(mid)

    intra_work_examples = []
    for work, mids in work_memories.items():
        if len(mids) < 2:
            continue
        # Sample pairs within the same work
        n_pairs = min(3, len(mids) // 2)
        sampled = random.sample(mids, min(n_pairs * 2, len(mids)))
        for j in range(0, len(sampled) - 1, 2):
            src, tgt = sampled[j], sampled[j+1]
            if src in content_cache and tgt in content_cache:
                intra_work_examples.append(make_sft(
                    f"Write more in the style of {work}",
                    content_cache[tgt],
                    system_extra=f"Style: {work}. Continue in this work's distinctive voice.",
                    source="intra_work",
                    meta={"work": work},
                ))

    print(f"[optimal] Graph continuation: {len(graph_examples)}", file=sys.stderr)
    print(f"[optimal] Intra-work: {len(intra_work_examples)}", file=sys.stderr)

    # ================================================================
    # STEP 3: Add importance-weighted duplicates for high-value memories
    # ================================================================
    # Memories with importance > 0.9 get an extra training example
    high_importance = []
    for mid, imp in importance_cache.items():
        if imp > 0.9 and mid in content_cache:
            content = content_cache[mid]
            work = work_cache.get(mid, "General")
            # Create a "masterwork" variant
            high_importance.append(make_sft(
                f"Write your finest verse on this theme",
                content,
                system_extra=f"Style: {work}. This is a masterwork passage — write with full artistry.",
                source="high_importance",
                meta={"importance": round(imp, 3), "work": work},
            ))

    print(f"[optimal] High-importance extras: {len(high_importance)}", file=sys.stderr)

    # ================================================================
    # STEP 4: Combine everything
    # ================================================================
    all_sft = (
        enhanced +
        graph_examples +
        intra_work_examples +
        high_importance +
        adversarial +
        creative
    )
    random.shuffle(all_sft)

    # Write
    with open(args.out, "w") as f:
        for ex in all_sft:
            f.write(json.dumps(ex, ensure_ascii=False) + "\n")

    # ================================================================
    # REPORT
    # ================================================================
    counts = defaultdict(int)
    for ex in all_sft:
        src = ex.get("_meta", {}).get("prompt_source", "unknown")
        if src.startswith("graph_"):
            counts["Graph continuation"] += 1
        elif "adversarial" in src:
            counts["Adversarial"] += 1
        elif "creative" in src:
            counts["Creative"] += 1
        elif src == "intra_work":
            counts["Intra-work style"] += 1
        elif src == "high_importance":
            counts["High-importance"] += 1
        elif src == "gemma4_generated":
            counts["Enhanced (Gemma prompts)"] += 1
        else:
            counts["Other enhanced"] += 1

    sz = Path(args.out).stat().st_size
    dpo_path = training_dir / "shakespeare_dpo.jsonl"
    dpo_count = sum(1 for _ in open(dpo_path)) if dpo_path.exists() else 0

    print(f"\n{'='*70}", file=sys.stderr)
    print(f"  OPTIMAL DATASET — BUILT FROM ALL CONTEXT GRAPH SIGNALS", file=sys.stderr)
    print(f"{'='*70}", file=sys.stderr)
    print(f"  SFT Examples:", file=sys.stderr)
    for k, v in sorted(counts.items(), key=lambda x: -x[1]):
        print(f"    {k}: {v:,}", file=sys.stderr)
    print(f"    {'─'*40}", file=sys.stderr)
    print(f"    TOTAL SFT: {len(all_sft):,}", file=sys.stderr)
    print(f"  DPO Pairs: {dpo_count:,} (pre-built contrastive pairs)", file=sys.stderr)
    print(f"  GRAND TOTAL: {len(all_sft) + dpo_count:,}", file=sys.stderr)
    print(f"", file=sys.stderr)
    print(f"  How signals are used:", file=sys.stderr)
    print(f"    Content (2,698 memories)    → SFT training targets", file=sys.stderr)
    print(f"    13 embedder scores/memory   → Informed Gemma prompt generation", file=sys.stderr)
    print(f"    78 cross-corr/memory        → Encoded in DPO anomaly_kind", file=sys.stderr)
    print(f"    Constellation scores        → Work-style system prompts", file=sys.stderr)
    print(f"    {total_edges:,} typed edges          → {len(graph_examples):,} graph-continuation examples", file=sys.stderr)
    print(f"    Importance scores            → {len(high_importance):,} high-importance extras", file=sys.stderr)
    print(f"    12,567 contrastive pairs    → DPO training phase", file=sys.stderr)
    print(f"    Adversarial data            → {len(adversarial):,} robustness examples", file=sys.stderr)
    print(f"", file=sys.stderr)
    print(f"  Output: {args.out} ({sz/1e6:.1f} MB)", file=sys.stderr)
    print(f"{'='*70}", file=sys.stderr)


if __name__ == "__main__":
    main()
