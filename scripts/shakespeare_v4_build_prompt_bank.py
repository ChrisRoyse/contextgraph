def generate_category(spec: CategorySpec, seen: set[str], rng: random.Random) -> list[dict]:
    """Generate unique prompts for one category until target_count is reached
    or combinations exhaust. FAIL-FAST if cannot reach target."""
    out: list[dict] = []
    # Build all (template_idx, seed_idx) pairs and shuffle
    pairs = [(ti, si) for ti in range(len(spec.templates)) for si in range(len(spec.seeds))]
    rng.shuffle(pairs)

    for (ti, si) in pairs:
        if len(out) >= spec.target_count:
            break
        seed = spec.seeds[si]
        template = spec.templates[ti]
        try:
            prompt = template(seed)
        except Exception as e:
            raise RuntimeError(
                f"Template failed for category={spec.name} template_idx={ti} seed={seed!r}: {e}"
            ) from e
        if not isinstance(prompt, str) or len(prompt.strip()) < 5:
            raise RuntimeError(
                f"Template produced invalid prompt: category={spec.name} prompt={prompt!r}"
            )
        prompt = prompt.strip()
        if prompt in seen:
            continue
        if len(prompt) > 300:
            # Skip prompts that exceed max length (shouldn't happen with our seeds)
            continue
        seen.add(prompt)
        # Subcategory = seed ID (or string of tuple for foreign)
        sub = seed[0] if isinstance(seed, tuple) else seed
        out.append({
            "prompt_id": f"v4-{spec.name}-{len(out):05d}",
            "category": spec.name,
            "subcategory": sub[:80],
            "prompt": prompt,
            "template": f"template_idx_{ti}",
            "generator_version": "1.0",
        })
    if len(out) < spec.target_count:
        capacity = len(spec.templates) * len(spec.seeds)
        deficit = spec.target_count - len(out)
        cause = "capacity exhausted" if capacity <= spec.target_count else "cross-category dedup collisions"
        raise RuntimeError(
            f"[{spec.name}] FAILED to reach target: got {len(out)}/{spec.target_count}. "
            f"deficit={deficit}, cause={cause}, templates={len(spec.templates)}, "
            f"seeds={len(spec.seeds)}, capacity={capacity}"
        )
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--output", type=Path, default=OUTPUT)
    ap.add_argument("--seed", type=int, default=20260418)
    args = ap.parse_args()

    rng = random.Random(args.seed)
    seen: set[str] = set()
    all_records: list[dict] = []

    print(f"[v4-prompt-bank] targeting {sum(c.target_count for c in CATEGORIES)} prompts", file=sys.stderr)
    for spec in CATEGORIES:
        recs = generate_category(spec, seen, rng)
        all_records.extend(recs)
        print(f"  [{spec.name:20s}] {len(recs):5d}/{spec.target_count}  "
              f"capacity={len(spec.templates) * len(spec.seeds):5d}", file=sys.stderr)

    # Dedup sanity (should be 0 dupes because we track `seen` set)
    prompts = [r["prompt"] for r in all_records]
    if len(prompts) != len(set(prompts)):
        raise RuntimeError(f"DEDUP BROKEN: {len(prompts)} records but {len(set(prompts))} unique prompts")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    partial = args.output.with_suffix(args.output.suffix + ".partial")
    with partial.open("w", encoding="utf-8") as f:
        for r in all_records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    partial.replace(args.output)

    print(f"\n[v4-prompt-bank] wrote {len(all_records)} unique prompts to {args.output}",
          file=sys.stderr)
    print(f"[v4-prompt-bank] file size: {args.output.stat().st_size/1024:.1f} KB", file=sys.stderr)

    return 0


if __name__ == "__main__":
    sys.exit(main())
